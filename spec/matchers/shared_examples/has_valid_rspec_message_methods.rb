# frozen_string_literal: true

RSpec.shared_examples "has valid rspec message methods" do
  context "when the matcher returns a failure message to the dev" do
    subject(:configured_matcher) { matcher }

    before do
      case validator_sym
      when :aspect_ratio then matcher.rejecting(:square)
      when :attached then matcher
      when :processable_file then matcher
      when :limit then matcher.max(6)
      when :content_type then matcher.rejecting("image/png")
      when :dimension then matcher.width(75).height(75)
      when :duration then matcher.less_than_or_equal_to(7.minutes)
      when :with_audio then matcher
      when :size then matcher.less_than_or_equal_to(7.megabytes)
      when :total_size then matcher.less_than_or_equal_to(7.megabytes)
      when :pages then matcher.less_than_or_equal_to(7)
      end
    end


    let(:model_attribute) { :failure_message }
    let(:expected_failure_message) do
      case validator_sym
      when :aspect_ratio
        <<~FAILURE_MESSAGE
          is expected to validate aspect ratio of :#{model_attribute}
            the following aspect ratio should be rejected: :square
            but :square was accepted
        FAILURE_MESSAGE
      when :attached
        <<~FAILURE_MESSAGE
          is expected to validate attachment of :#{model_attribute}
        FAILURE_MESSAGE
      when :processable_file
        <<~FAILURE_MESSAGE
          is expected to validate the processable file of :#{model_attribute}
        FAILURE_MESSAGE
      when :limit
        <<~FAILURE_MESSAGE
          is expected to validate limit file of :#{model_attribute}
            but there seem to have issues with the matcher methods you used, since:
            validation failed when provided with 6 file(s)
            whereas it should have passed
        FAILURE_MESSAGE
      when :content_type
        <<~FAILURE_MESSAGE
          is expected to validate the content types of :#{model_attribute}
            the following content type should be rejected: :image/png
            but :image/png was accepted
        FAILURE_MESSAGE
      when :dimension
        <<~FAILURE_MESSAGE
          is expected to validate dimensions of :#{model_attribute}
            but there seem to have issues with the matcher methods you used, since:
            validation failed when provided with a 75x75px test image
            whereas it should have passed
        FAILURE_MESSAGE
      when :duration
        <<~FAILURE_MESSAGE
          is expected to validate file duration of :#{model_attribute}
            but there seem to have issues with the matcher methods you used, since:
            validation failed when provided with a 420 seconds test file
            whereas it should have passed
        FAILURE_MESSAGE
      when :with_audio
        <<~FAILURE_MESSAGE
          is expected to validate that :#{model_attribute} has an audio track
        FAILURE_MESSAGE
      when :size
        <<~FAILURE_MESSAGE
          is expected to validate file size of :#{model_attribute}
            but there seem to have issues with the matcher methods you used, since:
            validation failed when provided with a 7340032 bytes test file
            whereas it should have passed
        FAILURE_MESSAGE
      when :total_size
        <<~FAILURE_MESSAGE
          is expected to validate total file size of :#{model_attribute}
            but there seem to have issues with the matcher methods you used, since:
            validation failed when provided with a 7340032 bytes test file
            whereas it should have passed
        FAILURE_MESSAGE
      when :pages
        <<~FAILURE_MESSAGE
          is expected to validate file number of pages of :#{model_attribute}
            but there seem to have issues with the matcher methods you used, since:
            validation failed when provided with a 7 pages test file
            whereas it should have passed
        FAILURE_MESSAGE
      end[0..-2] # to remove last \n generated by the <<~ format
    end

    it { is_expected_to_have_failure_message(expected_failure_message) }
  end

  context "when the matcher returns a negated failure message to the dev" do
    subject(:configured_matcher) { matcher }

    before do
      case validator_sym
      when :aspect_ratio then matcher.allowing(:square)
      when :attached then matcher
      when :processable_file then matcher
      when :limit then matcher.min(1).max(5)
      when :content_type then matcher.allowing("image/png")
      when :dimension then matcher.width(150).height(150)
      when :duration then matcher.less_than_or_equal_to(5.minutes)
      when :with_audio then matcher
      when :size then matcher.less_than_or_equal_to(5.megabytes)
      when :total_size then matcher.less_than_or_equal_to(5.megabytes)
      when :pages then matcher.less_than_or_equal_to(5)
      end
    end


    let(:model_attribute) { :failure_message_when_negated }
    let(:expected_failure_message) do
      case validator_sym
      when :aspect_ratio
        <<~FAILURE_MESSAGE
          is expected not to validate aspect ratio of :#{model_attribute}
        FAILURE_MESSAGE
      when :attached
        <<~FAILURE_MESSAGE
          is expected not to validate attachment of :#{model_attribute}
        FAILURE_MESSAGE
      when :processable_file
        <<~FAILURE_MESSAGE
          is expected not to validate the processable file of :#{model_attribute}
        FAILURE_MESSAGE
      when :limit
        <<~FAILURE_MESSAGE
          is expected not to validate limit file of :#{model_attribute}
        FAILURE_MESSAGE
      when :content_type
        <<~FAILURE_MESSAGE
          is expected not to validate the content types of :#{model_attribute}
        FAILURE_MESSAGE
      when :dimension
        <<~MESSAGE
          is expected not to validate dimensions of :#{model_attribute}
        MESSAGE
      when :duration
        <<~FAILURE_MESSAGE
          is expected not to validate file duration of :#{model_attribute}
        FAILURE_MESSAGE
      when :with_audio
        <<~FAILURE_MESSAGE
          is expected not to validate that :#{model_attribute} has an audio track
        FAILURE_MESSAGE
      when :size
        <<~FAILURE_MESSAGE
          is expected not to validate file size of :#{model_attribute}
        FAILURE_MESSAGE
      when :total_size
        <<~FAILURE_MESSAGE
          is expected not to validate total file size of :#{model_attribute}
        FAILURE_MESSAGE
      when :pages
        <<~FAILURE_MESSAGE
          is expected not to validate file number of pages of :#{model_attribute}
        FAILURE_MESSAGE
      end[0..-2] # to remove last \n generated by the <<~ format
    end

    it { is_expected_to_have_failure_message_when_negated(expected_failure_message) }
  end

  context "when the matcher runs twice" do
    subject(:configured_matcher) { matcher }

    before do
      case validator_sym
      when :aspect_ratio then matcher.rejecting(:square)
      when :limit then matcher.max(6)
      when :content_type then matcher.rejecting("image/png")
      when :dimension then matcher.width(75).height(75)
      when :duration then matcher.less_than_or_equal_to(7.minutes)
      when :size, :total_size then matcher.less_than_or_equal_to(7.megabytes)
      when :pages then matcher.less_than_or_equal_to(7)
      end
    end

    let(:model_attribute) { :failure_message }

    it "does not repeat the failure message details" do
      configured_matcher.matches?(klass)
      first_failure_message = configured_matcher.failure_message

      configured_matcher.matches?(klass)
      expect(configured_matcher.failure_message).to eq(first_failure_message)
    end
  end

  context "when the dev asks for a description of the matcher" do
    subject(:description) { matcher.description }

    let(:model_attribute) { :failure_message_when_negated }

    it "returns a string containing the attribute name" do
      expect(subject).to match(/#{model_attribute}/)
    end
  end

  context "when the dev asks for a description of a chained matcher" do
    subject(:configured_matcher) { matcher.with_message("Custom message").on(:update) }

    before do
      case validator_sym
      when :aspect_ratio then matcher.allowing(:square)
      when :limit then matcher.min(1).max(5)
      when :content_type then matcher.allowing("image/png")
      when :dimension then matcher.width(150).height_min(100)
      when :duration then matcher.less_than_or_equal_to(5.minutes)
      when :size, :total_size then matcher.between(2.kilobytes..5.megabytes)
      when :pages then matcher.less_than_or_equal_to(5)
      end
    end

    let(:model_attribute) { :failure_message_when_negated }
    let(:expected_description) do
      {
        aspect_ratio: "validate the aspect ratios allowed on :#{model_attribute}, allowing :square",
        attached: "validate that :#{model_attribute} must be attached",
        processable_file: "validate that :#{model_attribute} is a processable file",
        limit: "validate the limit files of :#{model_attribute}, at least 1 file, at most 5 files",
        content_type: "validate the content types allowed on :#{model_attribute}, allowing image/png",
        dimension: "validate the image dimensions of :#{model_attribute}, width 150px, height at least 100px",
        duration: "validate file duration of :#{model_attribute}, less than or equal to 5 minutes",
        with_audio: "validate that :#{model_attribute} has an audio track",
        size: "validate file size of :#{model_attribute}, between 2 KB and 5 MB",
        total_size: "validate total file size of :#{model_attribute}, between 2 KB and 5 MB",
        pages: "validate file number of pages of :#{model_attribute}, less than or equal to 5 pages"
      }.fetch(validator_sym)
    end

    it "lists the chained qualifiers" do
      expect(configured_matcher.description).to eq(%(#{expected_description}, with message "Custom message", on :update))
    end

    # enforce_available_locales (Rails default) raises for a locale that is not
    # available, so the description must not ask I18n for :en.
    context "when :en is not an available locale" do
      around do |example|
        previous_locales, previous_locale = I18n.available_locales, I18n.locale
        I18n.available_locales = [ :fr ]
        I18n.locale = :fr
        example.run
      ensure
        I18n.available_locales = previous_locales
        I18n.locale = previous_locale
      end

      it "still describes the chain" do
        expect { configured_matcher.description }.not_to raise_error
      end
    end
  end
end
